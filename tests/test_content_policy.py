class BrokenPolicyTest(unittest.TestCase):
    """A policy that cannot be read must not silently switch itself off."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.dir = pathlib.Path(self._tmp.name)

    def bad_files(self):
        yield self.dir / "missing.json"
        broken = self.dir / "broken.json"
        broken.write_text("{not json", encoding="utf-8")
        yield broken
        empty = self.dir / "empty.json"
        empty.write_text(json.dumps({"rules": {"no_ai_signature": {"message": "m", "patterns": []}},
                                     "scope": {"bash_publishing_commands": [], "files": [], "mcp_tools": "x"}}))
        yield empty
        bad_regex = self.dir / "regex.json"
        data = json.loads(POLICY.read_text())
        data["rules"]["no_ai_signature"]["patterns"][0]["regex"] = "(unclosed"
        bad_regex.write_text(json.dumps(data))
        yield bad_regex

    def test_calls_likely_to_be_in_scope_ask_a_person(self):
        for path in self.bad_files():
            self.assertRaises(content_policy.PolicyError, content_policy.load_policy, path)
            for event in (bash('git commit -m "x"'), bash("gh pr create --title t"),
                          {"tool_name": "Write", "tool_input": {"file_path": "/r/.ai/tickets/T.md", "content": "x"}},
                          {"tool_name": "mcp__github__create_issue", "tool_input": {"body": "x"}}):
                out = content_policy.decide(event, path)
                self.assertEqual(out["hookSpecificOutput"]["permissionDecision"], "ask", (path.name, event))
                self.assertIn("could not be read", out["hookSpecificOutput"]["permissionDecisionReason"])

    def test_unrelated_calls_are_left_alone(self):
        for path in self.bad_files():
            self.assertIsNone(content_policy.decide(bash("ls -la"), path))
            self.assertIsNone(content_policy.decide({"tool_name": "Write", "tool_input": {
                "file_path": "/r/src/app.py", "content": "x"}}, path))


class HookTest(unittest.TestCase):
    def run_main(self, text):
        out, err = io.StringIO(), io.StringIO()
        code = pre_tool_use.main(io.StringIO(text), out, err)
        return code, out.getvalue(), err.getvalue()

    def test_a_signed_commit_is_denied_as_json(self):
        code, out, _ = self.run_main(json.dumps(bash('git commit -m "Signed by AI"')))
        self.assertEqual(code, 0)
        self.assertEqual(json.loads(out)["hookSpecificOutput"]["permissionDecision"], "deny")

    def test_a_clean_call_prints_nothing(self):
        code, out, _ = self.run_main(json.dumps(bash('git commit -m "fix: nulls"')))
        self.assertEqual((code, out), (0, ""))

    def test_input_that_is_not_json_does_not_crash(self):
        code, out, err = self.run_main("not json")
        self.assertEqual((code, out), (0, ""))
        self.assertIn("not JSON", err)

    def test_a_crashing_check_asks_a_person(self):
        original = content_policy.decide
        content_policy.decide = lambda event: 1 / 0
        try:
            code, out, _ = self.run_main(json.dumps(bash("ls")))
        finally:
            content_policy.decide = original
        self.assertEqual(code, 0)
        self.assertEqual(json.loads(out)["hookSpecificOutput"]["permissionDecision"], "ask")

    def test_it_runs_as_a_script_the_way_claude_code_runs_it(self):
        signed = subprocess.run([sys.executable, str(ROOT / "hooks" / "pre_tool_use.py")],
                                input=json.dumps(bash('gh pr create --body "Signed by AI"')),
                                capture_output=True, text=True)
        self.assertEqual(signed.returncode, 0, signed.stderr)
        self.assertEqual(json.loads(signed.stdout)["hookSpecificOutput"]["permissionDecision"], "deny")
        clean = subprocess.run([sys.executable, str(ROOT / "hooks" / "pre_tool_use.py")],
                               input=json.dumps(bash("git status")), capture_output=True, text=True)
        self.assertEqual((clean.returncode, clean.stdout), (0, ""))


class RegistrationAndSettingsTest(unittest.TestCase):
    def test_the_plugin_registers_the_policy_hook_for_the_tools_it_inspects(self):
        config = json.loads((ROOT / "hooks" / "hooks.json").read_text())
        entries = config["hooks"]["PreToolUse"]
        self.assertEqual(len(entries), 1)
        matcher = re.compile(entries[0]["matcher"])
        for tool in ("Bash", "Read", "Grep", "Glob", "Write", "Edit", "MultiEdit", "NotebookEdit",
                     "mcp__github__create_issue"):
            self.assertTrue(matcher.fullmatch(tool) or matcher.match(tool), tool)
        for tool in ("WebFetch", "Task", "TodoWrite"):
            self.assertIsNone(matcher.fullmatch(tool), tool)
        handler = entries[0]["hooks"][0]
        self.assertEqual(handler["type"], "command")
        self.assertGreater(handler["timeout"], 0)
        script = handler["command"].replace("${CLAUDE_PLUGIN_ROOT}", str(ROOT)).split('"')[1]
        self.assertTrue(pathlib.Path(script).is_file(), script)

    def test_claude_codes_own_attribution_is_switched_off_here_and_in_the_template(self):
        for path in (ROOT / ".claude" / "settings.json",
                     ROOT / "templates" / "client-project" / ".claude" / "settings.json"):
            settings = json.loads(path.read_text())
            self.assertEqual(settings["attribution"], {"commit": "", "pr": "", "sessionUrl": False}, str(path))

    def test_agents_are_told_not_to_route_around_a_policy(self):
        self.assertIn("Policies are not obstacles to route around", (ROOT / "AGENTS.md").read_text())

    def test_the_rule_is_stated_for_agents_here_and_in_every_new_project(self):
        for path in (ROOT / "AGENTS.md", ROOT / "templates" / "AGENTS.md"):
            self.assertIn("No AI signature", path.read_text(), str(path))

    def test_nothing_the_framework_ships_tells_an_agent_to_sign_its_work(self):
        policy = content_policy.load_policy(POLICY)
        exempt = {ROOT / "AGENTS.md", ROOT / "templates" / "AGENTS.md"}
        hits = []
        for folder in ("skills", "commands", "agents", "standards", "templates", "inbox"):
            for path in (ROOT / folder).rglob("*"):
                if path.is_file() and path not in exempt and path.suffix in (".md", ".yaml", ".json", ".sh"):
                    for name, matched in content_policy.find_signatures(path.read_text(encoding="utf-8"), policy):
                        hits.append(f"{path.relative_to(ROOT)}: {name}: {matched}")
        self.assertEqual(hits, [])



def bash(command, cwd=None):
    return {"tool_name": "Bash", "tool_input": {"command": command}, "cwd": str(cwd or ROOT)}


def verdict(event, path=POLICY):
    out = content_policy.decide(event, path)
    return out["hookSpecificOutput"]["permissionDecision"] if out else None


class PolicyFileTest(unittest.TestCase):
    def test_it_loads_and_every_pattern_has_an_example(self):
        policy = content_policy.load_policy(POLICY)
        names = [name for name, _ in policy.patterns]
        self.assertEqual(len(names), len(set(names)))
        self.assertEqual(set(names), set(SIGNED), "every pattern needs a signed example, and the reverse")

    def test_every_signed_example_is_found_by_its_own_pattern(self):
        policy = content_policy.load_policy(POLICY)
        for name, examples in SIGNED.items():
            for text in examples:
                self.assertIn(name, [n for n, _ in content_policy.find_signatures(text, policy)], text)

    def test_clean_text_is_never_flagged(self):
        policy = content_policy.load_policy(POLICY)
        for text in CLEAN:
            self.assertEqual(content_policy.find_signatures(text, policy), [], text)


class ShellCommandTest(unittest.TestCase):
    def test_publishing_commands_with_a_signature_are_denied(self):
        for command in (
            'git commit -m "fix: nulls" -m "Co-Authored-By: Claude <noreply@anthropic.com>"',
            "git commit -F - <<'EOF'\nfix: nulls\n\nCo-Authored-By: Claude <noreply@anthropic.com>\nEOF",
            'cd repo && git commit -m "x" -m "\U0001F916 Generated with Claude Code"',
            "git -C /tmp/r commit -m 'x\n\nGenerated with Claude Code'",
            'FOO=1 git commit -m "Signed by AI"',
            'sudo git tag -a v1 -m "Published by AI"',
            'gh pr create --title t --body "Done.\n\n\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)"',
            'gh issue comment 3 --body "Signed by AI"',
            'gh api repos/o/r/issues -f body="Edited by an AI assistant"',
            'git merge feature -m "Merged by Claude"',
        ):
            self.assertEqual(verdict(bash(command)), "deny", command)

    def test_the_reason_names_the_rule_the_text_and_the_pattern(self):
        out = content_policy.decide(bash('git commit -m "Signed by AI"'), POLICY)["hookSpecificOutput"]
        self.assertEqual(out["hookEventName"], "PreToolUse")
        reason = out["permissionDecisionReason"]
        for part in ("CP-01", "Signed by AI", "sign-off-by-ai", "commit, pull request or issue command"):
            self.assertIn(part, reason)
        self.assertNotIn("{matched}", reason)
        self.assertNotIn("{where}", reason)

    def test_commands_that_only_read_or_are_not_publishing_pass(self):
        for command in (
            'git commit -m "fix: handle nulls"',
            "git commit --amend --no-edit",
            'git log --grep="Co-Authored-By: Claude"',
            'grep -rn "Generated with Claude Code" .',
            'echo "Signed by AI" > notes.txt',
            "git diff --stat",
            "python3 -m unittest discover -s tests",
            'gh pr list --search "Generated with Claude Code"',
            "ls",
        ):
            self.assertIsNone(verdict(bash(command)), command)

    def test_a_message_file_is_read(self):
        with tempfile.TemporaryDirectory() as tmp:
            tmp = pathlib.Path(tmp)
            (tmp / "signed.txt").write_text("fix\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n")
            (tmp / "clean.txt").write_text("fix: handle nulls\n")
            self.assertEqual(verdict(bash("git commit -F signed.txt", tmp)), "deny")
            self.assertEqual(verdict(bash("git commit --file=signed.txt", tmp)), "deny")
            self.assertEqual(verdict(bash(f"gh pr create --title t --body-file {tmp}/signed.txt", tmp)), "deny")
            self.assertIsNone(verdict(bash("git commit -F clean.txt", tmp)))
            self.assertIsNone(verdict(bash("git commit -F missing.txt", tmp)))
            self.assertIsNone(verdict(bash("git commit -F -", tmp)))


class FileWriteTest(unittest.TestCase):
    def write(self, path, content):
        return {"tool_name": "Write", "tool_input": {"file_path": path, "content": content}}

    def edit(self, path, old, new):
        return {"tool_name": "Edit", "tool_input": {"file_path": path, "old_string": old, "new_string": new}}

    def test_ticket_decision_and_runbook_notes_are_protected(self):
        for path in ("/work/repo/.ai/tickets/T-1.md", ".ai/adr/ADR-1.md", "/w/r/.ai/runbooks/rerun.md",
                     "/w/r/.git/COMMIT_EDITMSG", "C:\\w\\r\\.ai\\tickets\\T-2.md"):
            self.assertEqual(verdict(self.write(path, "# Note\n\nSigned by AI\n")), "deny", path)
            self.assertIsNone(verdict(self.write(path, "# Note\n\nPlain text.\n")), path)

    def test_other_files_are_not_inspected(self):
        for path in ("/w/r/README.md", "/w/r/tests/test_x.py", "/w/r/docs/notes.md", "/w/r/src/ai/tickets_x.py"):
            self.assertIsNone(verdict(self.write(path, "Signed by AI")), path)

    def test_a_signature_can_be_removed(self):
        path = "/w/r/.ai/tickets/T-1.md"
        self.assertEqual(verdict(self.edit(path, "x", "Edited by Claude")), "deny")
        self.assertIsNone(verdict(self.edit(path, "Edited by Claude", "")))

    def test_multi_edit_is_checked_per_edit(self):
        path = "/w/r/.ai/adr/ADR-1.md"
        clean = {"tool_name": "MultiEdit", "tool_input": {"file_path": path, "edits": [
            {"old_string": "a", "new_string": "b"}, {"old_string": "Signed by AI", "new_string": ""}]}}
        signed = {"tool_name": "MultiEdit", "tool_input": {"file_path": path, "edits": [
            {"old_string": "a", "new_string": "b"}, {"old_string": "c", "new_string": "Signed by AI"}]}}
        self.assertIsNone(verdict(clean))
        self.assertEqual(verdict(signed), "deny")


